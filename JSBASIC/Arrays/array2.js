let arr =[1,2,3,4,5];

console.log(arr.length);//length is not function 

arr.push(10);// add element at the end
console.log(arr);

arr.pop(); // remove element from the end
console.log(arr);

arr.shift(); // remove the element from the start
console.log(arr);

arr.unshift(100);//add element at the start
console.log(arr);

arr.reverse();
console.log(arr);

console.log(arr.indexOf(100));//return the index of the elements